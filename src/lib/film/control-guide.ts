export function controlHelp(label:string,tool?:ToolId):string|undefined{
 if(label==='Сила')return 'Сила ореолов вокруг ярких объектов. Ноль убирает их вклад.';
 if(label==='Размер')return tool==='crop'?'Размер сохраняемой области кадра. Положение задаётся отдельно по X и Y.':'Ширина ореолов вокруг ярких участков; не меняет яркость самого источника.';
 if(label==='Размытие')return 'Смягчает структуру выбранного эффекта. Для зерна это сглаживание после формирования частиц.';
 if(help[label])return help[label];
 if(/^γ [RGB]$/.test(label))return 'Коэффициент проявки цветного канала бумаги. Меняет её кривую при включённой химии.';
 if(/слои γ|канал γ|эмульсии γ/.test(label))return 'Коэффициент проявки выбранного слоя или канала: выше 1 усиливает, ниже 1 смягчает его кривую.';
 if(label.startsWith('RMS'))return 'Гранулярность при апертуре 48 мкм: больше — заметнее зерно. Размер частиц рассчитывается из модели слоёв.';
 if(label.startsWith('Равномерность '))return 'Равномерность образования частиц в этом канале. Для Ч/Б используется один канал эмульсии.';
 if(label.startsWith('Минимальная плотность'))return 'Плотность, участвующая в образовании зерна даже при небольшой экспозиции.';
 if(label.startsWith('Размер частиц ·'))return 'Относительный размер частиц подслоя. Разные подслои дают разную фактуру при разной плотности.';
 if(label.startsWith('Радиус резкости плотности'))return 'Ширина усиления деталей в плотности эмульсии после зерна.';
 if(label.startsWith('Усиление резкости плотности'))return 'Сила повышения резкости плотности. Суммарная плотность канала сохраняется.';
 if(label.startsWith('Насыщение донора'))return 'Предел выделения ингибитора развивающимся слоем негатива.';
 if(label.startsWith('Насыщение приёмника'))return 'Предел реакции принимающего слоя слайдовой плёнки на ингибитор.';
 if(label.startsWith('Хвост диффузии'))return 'Дальность медленно затухающего распространения ингибитора за пределами основного радиуса.';
 if(label.startsWith('Доля хвоста'))return 'Доля длинного хвоста в общем распространении ингибитора.';
 if(label==='Циан основы'||label==='Маджента основы'||label==='Жёлтый основы')return 'Масштаб выбранной составляющей спектральной плотности основы. Нейтральное значение — 1.';
 if(label.startsWith('Масштаб '))return label.includes('PSF')?'Радиус оптического рассеяния фильтра.':'Относительный размер частиц в выбранном цветовом канале прежней модели зерна.';
 if(label.startsWith('Диффузия'))return 'Оптический рассеивающий фильтр: мягкость и свечение до следующего этапа обработки.';
 return undefined;
}
